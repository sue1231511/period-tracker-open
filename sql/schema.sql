-- 三张表都开 RLS 且不配任何规则：匿名 key / publishable key 完全读写不到，
-- 只有服务器用的服务端密钥（sb_secret_ 或 service_role）能访问。
-- 数据只经过本服务器，浏览器拿不到任何数据库密钥。

-- 经期记录。notes = 'marked' 表示「仅标记」，不参与周期计算。
create table if not exists public.period_records (
  id serial primary key,
  start_date date not null,
  notes text default '',
  duration integer default 5
);
create index if not exists period_records_start_date_idx on public.period_records (start_date);
alter table public.period_records enable row level security;

-- 排卵期记录
create table if not exists public.ovulation_records (
  id bigint generated by default as identity primary key,
  ovulation_date date not null,
  notes text default '',
  created_at timestamptz default now()
);
create index if not exists ovulation_records_date_idx on public.ovulation_records (ovulation_date);
alter table public.ovulation_records enable row level security;

-- OAuth 客户端、授权码、令牌、网页登录会话。service 字段区分不同服务，可以和别的自建 MCP 共用这张表。
create table if not exists public.mcp_oauth_store (
  id uuid primary key default gen_random_uuid(),
  service text not null,
  record_type text not null,
  key text not null,
  client_id text,
  client_name text,
  redirect_uris jsonb,
  redirect_uri text,
  code_challenge text,
  code_challenge_method text,
  scope text,
  expires_at timestamptz,
  created_at timestamptz not null default now()
);
create index if not exists mcp_oauth_store_lookup_idx on public.mcp_oauth_store (service, record_type, key);
alter table public.mcp_oauth_store enable row level security;

